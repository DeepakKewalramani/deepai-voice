//! The provider catalog, as data. Facts come from research R.4
//! (`docs/research/providers-findings.md`, 31 Oct 2026) and R.10
//! (`docs/research/providers-india-findings.md`, 1 Nov 2026), FACT rows only.
//! An entry is `Verified` only when its key facts are FACT in those notes.
//! To add a provider, add one `CatalogEntry` below; the tests check the invariants.
//! OpenAI's speech output models are deliberately absent: R.4 records their shutdown.

use super::{AuthStyle, Capability, EntryStatus, Setup, Tri};
use serde::Serialize;
use std::borrow::Cow;

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CatalogEntry {
    pub id: &'static str,
    pub capability: Capability,
    pub name: &'static str,
    pub vendor: &'static str,
    /// Adapter kind written to settings.json (`adapter`).
    pub adapter: &'static str,
    pub base_url_default: Option<&'static str>,
    #[serde(rename = "authStyle")]
    pub auth: AuthStyle,
    /// Model written to settings.json on connect. Empty when R.4 names none.
    pub default_model: &'static str,
    pub languages: &'static str,
    pub hindi: Tri,
    pub streaming: Tri,
    pub price: &'static str,
    /// Vendor documentation. Always https; opened only by catalog id.
    pub docs_url: &'static str,
    pub status: EntryStatus,
    pub setup: Setup,
    pub note: &'static str,
}

const fn header(name: &'static str) -> AuthStyle {
    AuthStyle::Header(Cow::Borrowed(name))
}

